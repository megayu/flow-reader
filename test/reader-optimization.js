function testEpubHrefComparisonHandlesEncodedSpinePaths() {
  assert.strictEqual(
    typeof noteLinks.sameHref,
    'function',
    'Expected one shared href comparison helper for reader paths',
  )

  assert.strictEqual(
    noteLinks.sameHref(
      'Text/%2A%3Achapter%3Aone.xhtml',
      'Text/*:chapter:one.xhtml',
    ),
    true,
    'decoded NCX targets must match encoded OPF spine hrefs',
  )

  assert.strictEqual(
    noteLinks.sameHref(
      'http://localhost:7127/OEBPS/Images/%2A%3Aplate%3A1.jpg',
      'Images/*:plate:1.jpg',
    ),
    true,
    'absolute image URLs must match package-relative resource hrefs',
  )
}

function testDuplicateIllustrationFilterHidesFirstAndRepeatedCandidates() {
  assert.strictEqual(
    typeof imageFilters.createDuplicateIllustrationFilter,
    'function',
    'Expected duplicate illustration filtering to be testable',
  )

  const firstSection = {
    images: [
      {
        hiddenByDefault: false,
        index: 0,
        src: '../Images/repeated%20art.jpg',
      },
      {
        hiddenByDefault: false,
        index: 1,
        src: '../Images/unique.jpg',
      },
    ],
  }
  const secondSection = {
    images: [
      {
        hiddenByDefault: false,
        index: 0,
        src: '../Images/repeated art.jpg',
      },
    ],
  }

  const filter = imageFilters.createDuplicateIllustrationFilter()
  assert.strictEqual(filter.applyToSection(firstSection), false)
  assert.strictEqual(filter.applyToSection(secondSection), true)

  assert.deepStrictEqual(firstSection.images[0], {
    hiddenByDefault: true,
    index: 0,
    reason: 'duplicate',
    src: '../Images/repeated%20art.jpg',
  })
  assert.deepStrictEqual(secondSection.images[0], {
    hiddenByDefault: true,
    index: 0,
    reason: 'duplicate',
    src: '../Images/repeated art.jpg',
  })
  assert.strictEqual(firstSection.images[1].hiddenByDefault, false)
}

