function testZoomMediaUsesScaledContentColumnWidth() {
  assert.strictEqual(
    typeof styles.createZoomMediaMaxInlineSize,
    'function',
    'Expected zoom media size to be calculated by a testable helper',
  )
  assert.strictEqual(
    typeof styles.createZoomMediaCss,
    'function',
    'Expected zoom media CSS to be generated by a testable helper',
  )

  const source = styles.createZoomLayoutBodyStyleSource(
    {
      name: 'reflowable',
      width: 1000,
      height: 800,
      columnWidth: 460,
      gap: 40,
    },
    'horizontal',
  )

  assert.strictEqual(styles.createZoomMediaMaxInlineSize(source, 2), 210)
  assert.match(
    styles.createZoomMediaCss(source, 2),
    /max-inline-size:\s*210px !important/,
    'zoomed media must fit within the scaled single-page content column',
  )
}

function testDefinitionsAreNormalizedConsistently() {
  assert.strictEqual(
    typeof annotation.normalizeDefinition,
    'function',
    'Expected shared definition normalization',
  )
  assert.strictEqual(
    typeof annotation.compareDefinition,
    'function',
    'Expected shared definition comparison',
  )

  assert.strictEqual(
    annotation.normalizeDefinition('  Café\n\tAU   Lait  '),
    'Café AU Lait',
  )
  assert.strictEqual(
    annotation.compareDefinition(' café au lait ', 'CAFÉ\nAU\tLAIT'),
    true,
  )
}

